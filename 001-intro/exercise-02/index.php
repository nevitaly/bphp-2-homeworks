<?php

// 1. Выводим название файла и номер текущей строки
echo "Название файла: " . basename(__FILE__) . PHP_EOL;
echo "Номер строки: " . __LINE__ . PHP_EOL;

// 2. Создаём многострочную переменную через heredoc
$text = <<<TEXT
Это первая строка текста.
Это вторая строка текста.
Это третья строка текста.
TEXT;

echo $text . PHP_EOL;

// 3. Создаём фразу из двух строковых переменных
$language = "PHP";
$description = "интересный язык программирования";

echo "$language — $description." . PHP_EOL;
